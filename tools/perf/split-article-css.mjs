// Derives src/styles/article.css from src/styles/landing-builder.css.
//
// The article pages (ArticleLayout) use a small part of the landing-page stylesheet. This keeps only the rules
// whose selector matches an element on at least one built article page, in the original order and with the
// selectors byte-identical, so the cascade seen by those pages does not change.
//
// Usage (needs a built `dist/` served over http and a Chrome binary):
//   PUPPETEER_CORE=/path/to/puppeteer-core/lib/puppeteer/puppeteer-core.js \
//   CHROME_PATH="/Applications/Google Chrome.app/Contents/MacOS/Google Chrome" \
//   node tools/perf/split-article-css.mjs http://localhost:4501
//
// Pseudo-classes / pseudo-elements are stripped before matching, which can only keep MORE rules (conservative).
import fs from 'node:fs';
import postcss from 'postcss';

const base = process.argv[2];
if (!base) throw new Error('usage: split-article-css.mjs <baseUrl of a served dist>');
const { default: puppeteer } = await import(process.env.PUPPETEER_CORE || 'puppeteer-core');

const SRC = 'src/styles/landing-builder.css';
const OUT = 'src/styles/article.css';
const slugs = fs
  .readdirSync('src/pages/landing-builder/articulos')
  .filter((f) => f.endsWith('.astro') && f !== 'index.astro')
  .map((f) => f.replace(/\.astro$/, ''));
const urls = slugs.map((s) => `${base}/landing-builder/articulos/${s}/`);

const root = postcss.parse(fs.readFileSync(SRC, 'utf8'));
const selectors = new Set();
root.walkRules((rule) => {
  if (rule.parent?.type === 'atrule' && /keyframes$/i.test(rule.parent.name)) return;
  rule.selectors.forEach((s) => selectors.add(s));
});

const strip = (sel) => {
  let s = sel.replace(/::?[a-zA-Z-]+(\((?:[^()]|\([^()]*\))*\))?/g, '').trim();
  if (!s || /[>+~]$/.test(s)) s += '*';
  return s.replace(/\s+/g, ' ');
};

const browser = await puppeteer.launch({
  executablePath: process.env.CHROME_PATH,
  headless: 'new',
});
const matched = new Set();
const list = [...selectors];
for (const url of urls) {
  const page = await browser.newPage();
  await page.goto(url, { waitUntil: 'load' });
  const hits = await page.evaluate((entries) => {
    const out = [];
    for (const [orig, stripped] of entries) {
      try {
        if (document.querySelector(stripped)) out.push(orig);
      } catch {
        out.push(orig); // unparsable once stripped: keep to stay safe
      }
    }
    return out;
  }, list.map((s) => [s, strip(s)]));
  hits.forEach((h) => matched.add(h));
  await page.close();
}
await browser.close();

// 1) keep rules with at least one matching selector
root.walkRules((rule) => {
  if (rule.parent?.type === 'atrule' && /keyframes$/i.test(rule.parent.name)) return;
  if (!rule.selectors.some((s) => matched.has(s))) rule.remove();
});
// 2) keep @keyframes only when a surviving declaration references them
const used = root.toString();
root.walkAtRules(/keyframes$/i, (at) => {
  if (!new RegExp(`\\b${at.params}\\b`).test(used.replace(at.toString(), ''))) at.remove();
});
// 3) drop empty at-rules and all comments (they described sections that are gone)
root.walkAtRules((at) => {
  if (at.nodes && at.nodes.length === 0) at.remove();
});
root.walkComments((c) => c.remove());

const header = `/* GENERATED by tools/perf/split-article-css.mjs from landing-builder.css. Do not edit by hand.
   Only the rules that match an element on the 8 article pages (ArticleLayout); selectors are byte-identical
   and the original order is kept. Regenerate after changing landing-builder.css. */\n`;
const css = header + root.toString().replace(/\n{3,}/g, '\n\n').trim() + '\n';
fs.writeFileSync(OUT, css);
console.log(`${OUT}: ${css.length} bytes from ${fs.statSync(SRC).size} (${urls.length} pages, ${matched.size}/${selectors.size} selectors matched)`);
